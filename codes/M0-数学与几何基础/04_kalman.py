import numpy as np


# =====================================================================
# 一、误差传播：一阶泰勒展开
# =====================================================================

def f(v):
    """
    一个非线性函数，模拟"输入两个量、输出两个量"的传感器链路。

        y1 = x1 · x2
        y2 = x1 / x2

    选它是因为：有乘法（放大误差）、有除法（对误差很敏感），
    正好能体现"一阶近似什么时候不太准"。
    """
    return np.array([v[0] * v[1], v[0] / v[1]])


def demo_propagation():
    """
    比较两种算法，看它们算出的协方差是否一致：

    解析法（一阶传播）：
        y = f(x)  =>  Σ_y ≈ J · Σ_x · J^T
        这里 J 是 f 对 x 的雅可比：
            J = [[∂y1/∂x1, ∂y1/∂x2],
                 [∂y2/∂x1, ∂y2/∂x2]]
              = [[x2,       x1     ],
                 [1/x2,    -x1/x2²  ]]

    蒙特卡洛（数值法）：
        从 N(μ, Σ) 里抽 20 万个样本，每个都过一遍 f，
        再统计输出样本的协方差 —— 不依赖线性化，就是慢。

    两者接近，说明在这个噪声水平下"一阶近似够用"。
    """
    print("== 1. 误差传播：一阶泰勒 vs 蒙特卡洛 ==")

    mu = np.array([2.0, 4.0])                   # 输入均值
    Sig = np.array([[0.04, 0.01],               # 输入协方差：对角是方差
                    [0.01, 0.09]])              # 非对角 0.01 表示两者相关

    # 在均值处算雅可比（这就是"线性化点"）
    J = np.array([[mu[1], mu[0]],
                  [1.0 / mu[1], -mu[0] / mu[1] ** 2]])
    Sig_y = J @ Sig @ J.T                       # 误差传播公式

    # 蒙特卡洛：抽样本 -> 过函数 -> 统计协方差
    rng = np.random.default_rng(2)
    samples = rng.multivariate_normal(mu, Sig, 200_000)
    fy = np.array([f(s) for s in samples])      # 每个样本算一次输出
    Sig_mc = np.cov(fy.T)                       # np.cov 默认按列是变量

    print("解析传播 Σ_y =\n", Sig_y.round(5))
    print("蒙特卡洛 Σ_y =\n", Sig_mc.round(5))
    print(f"相对误差 = {np.abs(Sig_y - Sig_mc).max() / np.abs(Sig_mc).max():.1%}\n")


# =====================================================================
# 二、两个高斯融合：这就是 KF 的"更新"一步
# =====================================================================

def fuse(m1, s1, m2, s2):
    """
    一维高斯融合：先验 N(m1, s1) + 观测 N(m2, s2) -> 后验

    推导：两个高斯相乘还是高斯，指数部分配方即可得到
        K = s1 / (s1 + s2)              观测占的权重
        x = m1 + K·(m2 − m1)            加权平均
        P = (1 − K)·s1                  融合后的方差（一定比两者都小）

    记住：K 是"观测的话语权"，取值范围 0~1。
        s2 越小（观测越准） -> K 越接近 1
        s2 越大（观测越差） -> K 越接近 0

    参数：m1,s1 先验均值/方差；m2,s2 观测均值/方差
    返回：融合后的均值、方差、K
    """
    K = s1 / (s1 + s2)
    return m1 + K * (m2 - m1), (1 - K) * s1, K


def demo_fuse():
    print("== 2. 两个高斯融合：K 就是观测的话语权 ==")
    m, p, K = fuse(0.0, 1.0, 2.0, 1.0)
    print(f"先验 N(0,1) + 观测 z=2 (R=1) -> x={m:.3f}, P={p:.3f}, K={K:.3f}\n")

    # 固定先验，只改观测方差 R，观察 K 的变化
    print(f"{'R':>6}{'K':>9}{'x':>9}{'P':>9}")
    for R in [0.01, 0.1, 1.0, 10.0, 100.0]:
        m, p, K = fuse(0.0, 1.0, 2.0, R)
        print(f"{R:>6}{K:>9.4f}{m:>9.3f}{p:>9.3f}")
    print("→ R 越小（观测越准），K 越接近 1\n")


# =====================================================================
# 三、卡尔曼滤波（一维位置 + 速度）
# =====================================================================

def demo_kalman():
    """
    常速度模型：
        状态 x = [位置, 速度]^T
        预测 x_k = F·x_{k−1} + 模型噪声   F = [[1,1],[0,1]]
        观测 z_k = H·x_k + 观测噪声       H = [1, 0]（只测位置）

    五个公式（预测 2 个 + 更新 3 个）：
        x⁻ = F·x                预测状态
        P⁻ = F·P·F^T + Q        预测协方差（不确定性会变大）
        K  = P⁻·H^T / (H·P⁻·H^T + R)    增益
        x  = x⁻ + K·(z − H·x⁻)  用"新息"修正
        P  = (I − K·H)·P⁻       更新协方差（不确定性变小）

    这个例子的看点：只测位置，但速度也能被估出来 ——
    因为模型告诉它"位置的变化率就是速度"。
    """
    print("== 3. 常速度模型 KF（只测位置，速度靠模型推） ==")

    F = np.array([[1.0, 1.0], [0.0, 1.0]])   # 位置 += 速度 × 1 秒
    Q = np.diag([0.01, 0.04])                # 模型噪声：速度比位置更不确定
    H = np.array([[1.0, 0.0]])               # 观测矩阵：只看到位置
    R = np.array([[0.5]])                    # 观测噪声方差

    x = np.array([0.0, 0.0])                 # 初始状态 [位置, 速度]
    P = np.eye(2)                            # 初始协方差（"完全不知道"）

    print(f"{'z':>6}{'x_pos':>9}{'x_vel':>9}{'K0':>9}")
    for z in [1.0, 2.1, 2.9, 4.2, 5.1]:
        # --- 预测 ---
        x = F @ x
        P = F @ P @ F.T + Q

        # --- 更新 ---
        # 矩阵写法：K = P H^T (H P H^T + R)^{-1}
        K = P @ H.T @ np.linalg.inv(H @ P @ H.T + R)
        # 新息 = 观测 − 预测的观测；np.array([[z]]) 保持 (1,1) 形状
        innovation = np.array([[z]]) - H @ x
        x = x + (K @ innovation).ravel()     # ravel 把 (2,1) 拉平回 (2,)
        P = (np.eye(2) - K @ H) @ P

        print(f"{z:>6.1f}{x[0]:>9.3f}{x[1]:>9.3f}{K[0, 0]:>9.3f}")

    print(f"\n最终 x = {x.round(3)}  （真值应该是位置 5、速度 1 附近）")
    print(f"最终 P =\n{P.round(4)}\n")


