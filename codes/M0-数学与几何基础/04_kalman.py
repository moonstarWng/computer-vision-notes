# 四、马氏距离
# =====================================================================

def demo_mahalanobis():
    """
    马氏距离：d² = e^T · Σ^{-1} · e

    和欧氏距离的区别：先把误差按"各方向的不确定度"归一化。
    所以同样偏 10cm：
        σ = 1mm   -> d = 100，离谱到不该信
        σ = 20cm  -> d = 0.5，完全正常

    工程上常拿它做异常检测：2 维时 d > 2.45 就超过 95% 置信区间
    （卡方分布 χ²(2) 的 95% 分位数是 5.99，开根号就是 2.45）。
    """
    print("== 4. 马氏距离：按不确定度归一化 ==")
    e = np.array([0.10, 0.0])                       # 偏差向量：10cm

    for name, sigma in [("精确传感器 σ=1mm", 0.001), ("普通传感器 σ=20cm", 0.20)]:
        S = np.diag([sigma ** 2, sigma ** 2])       # 对角协方差
        d = float(np.sqrt(e @ np.linalg.inv(S) @ e))
        print(f"{name:<18} → 马氏距离 d = {d:6.2f}")
    print("（约 95% 置信门限：2 维卡方 5.99 → d≈2.45；超过就该怀疑是异常）")


